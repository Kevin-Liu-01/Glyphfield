/** Regenerate after upgrading the pinned MIT-licensed shaders dependency. */
import { writeFile } from 'node:fs/promises';
import { getAllShaders } from 'shaders/registry';
const infrastructure = {
  Group: 'Use Design Lab layer groups to compose effects.',
  HTMLInCanvas: 'Experimental Chrome-only DOM capture; use Design Lab text and image layers.',
  WebcamTexture: 'Camera capture is not enabled by selecting a material.',
  VideoTexture: 'Video input is a media source, not a standalone material.',
};
const entries = [];
for (const item of getAllShaders()) {
  const { default: definition } = await import(`shaders/core/${item.name}`);
  entries.push({
    id: `shader-effects-${item.name.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()}`,
    component: item.name,
    name: item.name.replace(/([a-z0-9])([A-Z])/g, '$1 $2'),
    category: item.category,
    description: item.description ?? item.name,
    requiresChild: !!definition.requiresChild,
    stateful: item.category === 'Interactive' || ['TimeTrail', 'ParticleField', 'KeyFrames', 'SmokeFill', 'Particles'].includes(item.name),
    infrastructure: infrastructure[item.name] ?? null,
    props: { ...(item.category === 'Shape Effects' ? { surface: { type: 'select', label: 'Surface', group: 'Framing', default: 'canvas', options: [{ label: 'Full canvas', value: 'canvas' }, { label: 'Shape', value: 'shape' }] } } : {}), ...(definition.requiresChild || item.name === 'ImageTexture' ? { sourceImage: { type: 'local-image', label: 'Source image', group: 'Source', default: '' } } : {}), ...Object.fromEntries(Object.entries(definition.props).map(([key, prop]) => [key, {
      default: prop.default === 'transparent' && [prop.ui?.type].flat().includes('color') ? '#00000000' : prop.ui?.options?.find(option => String(option.value).toLowerCase() === String(prop.default).toLowerCase())?.value ?? prop.default, ...prop.ui,
    }])) },
  });
}
await writeFile('src/lib/shaderEffectsCatalog.generated.json', JSON.stringify(entries) + '\n');
await writeFile('src/lib/shaderEffectsLoaders.generated.ts', '// Generated by scripts/generate-shader-effects.mjs; lazy chunks keep the GPU engine out of initial page loads.\nexport const shaderEffectsLoaders = {\n' + entries.map(e=>`  ${e.component}: () => import('shaders/core/${e.component}'),`).join('\n') + '\n};\n');
console.log(`Generated ${entries.length} components (${entries.filter(e=>!e.infrastructure).length} materials).`);
