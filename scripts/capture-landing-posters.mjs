#!/usr/bin/env node
/**
 * Captures the first frame of the landing hero shaders as small blurred posters.
 * The page paints these at once and fades to the live shaders when they draw.
 * Usage: node scripts/capture-landing-posters.mjs [--base=http://localhost:3012]
 * Writes src/app/landing-posters.css.
 */
import { writeFileSync } from 'node:fs';
import { chromium } from '@playwright/test';

const base = process.argv.find((arg) => arg.startsWith('--base='))?.slice(7) ?? 'http://localhost:3012';
// One capture per hero layout: the field's aspect ratio changes at these widths.
const FIELD_LAYOUTS = [
  { media: null, viewport: { height: 900, width: 1440 } },
  { media: '(max-width: 1199px)', viewport: { height: 900, width: 1024 } },
  { media: '(max-width: 760px)', viewport: { height: 844, width: 390 } },
];
const FIELD_POSTER_WIDTH = 64;
const MARK_POSTER_SIZE = 48;
// Hide everything above the shaders, and the mark's mask, so a capture holds only shader pixels.
const CAPTURE_CSS = `
  .marketing-v5-hero-studio, .marketing-v5-hero-field > :not(.marketing-v5-arc-field) { visibility: hidden !important; }
  .marketing-v5-hero-mark { mask-image: none !important; -webkit-mask-image: none !important; }
`;

async function downscaleToWebp(page, png, width) {
  return page.evaluate(async ({ data, width }) => {
    const image = await createImageBitmap(await (await fetch(`data:image/png;base64,${data}`)).blob());
    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = Math.round(width * image.height / image.width);
    const context = canvas.getContext('2d');
    context.imageSmoothingQuality = 'high';
    context.drawImage(image, 0, 0, canvas.width, canvas.height);
    return canvas.toDataURL('image/webp', 0.82);
  }, { data: png.toString('base64'), width });
}

async function capture(page, selector, width) {
  await page.waitForSelector(`${selector} [data-live-material-ready="true"] canvas`, { timeout: 30_000 });
  await page.waitForTimeout(400);
  return downscaleToWebp(page, await page.locator(selector).screenshot(), width);
}

const browser = await chromium.launch({
  args: ['--enable-gpu', '--use-angle=metal', '--ignore-gpu-blocklist'],
  channel: 'chromium',
});
const rules = [];
try {
  for (const [index, { media, viewport }] of FIELD_LAYOUTS.entries()) {
    // Reduced motion holds each shader on the frame it first draws.
    const page = await browser.newPage({ deviceScaleFactor: index === 0 ? 2 : 1, reducedMotion: 'reduce', viewport });
    await page.goto(`${base}/`);
    await page.addStyleTag({ content: CAPTURE_CSS });
    const field = await capture(page, '.marketing-v5-hero-grain-gradient', FIELD_POSTER_WIDTH);
    const rule = `.marketing-v5-hero-grain-gradient { --marketing-field-poster: url('${field}'); }`;
    rules.push(media ? `@media ${media} {\n  ${rule}\n}` : rule);
    if (index === 0) {
      const mark = await capture(page, '.marketing-v5-hero-mark', MARK_POSTER_SIZE);
      rules.push(`.marketing-v5-hero-mark { --marketing-field-poster: url('${mark}'); }`);
    }
    await page.close();
  }
} finally {
  await browser.close();
}
writeFileSync('src/app/landing-posters.css', `/* Generated by scripts/capture-landing-posters.mjs. First frames of the hero shaders. */\n${rules.join('\n')}\n`);
console.log('wrote src/app/landing-posters.css');
