// Measures the visible ink of every bundled logo and writes src/lib/logoArtwork.ts.
// Run after adding or replacing a file under public/brands/*/logos, public/brands/*/proof,
// or public/templates/logos:  node scripts/generate-logo-ink.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { chromium } from '@playwright/test';

const root = new URL('..', import.meta.url).pathname;
const publicDir = join(root, 'public');
const directories = [
  ...readdirSync(join(publicDir, 'brands')).flatMap((brand) => ['logos', 'proof'].map((folder) => `brands/${brand}/${folder}`)),
  'templates/logos',
];
const files = directories.flatMap((directory) => {
  try {
    return readdirSync(join(publicDir, directory)).filter((file) => file.endsWith('.svg')).map((file) => `/${directory}/${file}`);
  } catch {
    return [];
  }
}).sort();

function viewBoxAspect(svg) {
  const viewBox = /viewBox=["']\s*[-\d.]+[\s,]+[-\d.]+[\s,]+([\d.]+)[\s,]+([\d.]+)/.exec(svg);
  if (viewBox) return Number(viewBox[1]) / Number(viewBox[2]);
  const width = /<svg[^>]*\swidth=["']([\d.]+)/.exec(svg);
  const height = /<svg[^>]*\sheight=["']([\d.]+)/.exec(svg);
  return width && height ? Number(width[1]) / Number(height[1]) : 1;
}

const browser = await chromium.launch();
const page = await browser.newPage();
const bounds = {};
for (const path of files) {
  const svg = readFileSync(join(publicDir, path), 'utf8');
  const aspect = viewBoxAspect(svg);
  const width = aspect >= 1 ? 1600 : Math.round(1600 * aspect);
  const height = aspect >= 1 ? Math.round(1600 / aspect) : 1600;
  const source = `data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}`;
  const box = await page.evaluate(async ({ height, source, width }) => {
    const image = new Image(width, height);
    image.src = source;
    await image.decode();
    const canvas = document.createElement('canvas');
    canvas.width = width;
    canvas.height = height;
    const context = canvas.getContext('2d');
    context.drawImage(image, 0, 0, width, height);
    const pixels = context.getImageData(0, 0, width, height).data;
    let left = width; let top = height; let right = -1; let bottom = -1;
    for (let y = 0; y < height; y += 1) {
      for (let x = 0; x < width; x += 1) {
        if (pixels[(y * width + x) * 4 + 3] < 24) continue;
        if (x < left) left = x;
        if (x > right) right = x;
        if (y < top) top = y;
        if (y > bottom) bottom = y;
      }
    }
    if (right < 0) return null;
    return [left / width, top / height, (right + 1) / width, (bottom + 1) / height];
  }, { height, source, width });
  if (!box) continue;
  bounds[path] = { aspect: Math.round(aspect * 10000) / 10000, ink: box.map((value) => Math.round(value * 10000) / 10000) };
}
await browser.close();

const lines = Object.entries(bounds).map(([path, { aspect, ink }]) => `  '${path}': { aspect: ${aspect}, ink: [${ink.join(', ')}] },`);
writeFileSync(join(root, 'src/lib/logoArtwork.ts'), `// Generated by scripts/generate-logo-ink.mjs. Do not edit by hand.

export type LogoInkBox = readonly [left: number, top: number, right: number, bottom: number];

/** Bundled logo files: artwork width / height and the visible ink as fractions of the artwork box. */
export const LOGO_ARTWORK: Readonly<Record<string, { aspect: number; ink: LogoInkBox }>> = {
${lines.join('\n')}
};
`);
console.log(`${files.length} logos measured`);
