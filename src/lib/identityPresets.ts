function asset(
  id: string,
  label: string,
  path: string,
  surface: BrandAsset['surface'],
  type: BrandAsset['type'] = 'logo',
  usage?: string
): BrandAsset {
  return {
    alt: label,
    id,
    label,
    path,
    redistribution: type === 'proof' || type === 'reference' ? 'research-only' : 'bundled',
    surface,
    tags: id === 'identity-field' ? [type, 'brand-diagram'] : [type],
    type,
    usage,
  };
}

